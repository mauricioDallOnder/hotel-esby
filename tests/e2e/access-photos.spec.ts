import { expect, test } from "@playwright/test";
import { today, type Issue } from "../../lib/domain";

test("employee reports three photos; only direction changes the status", async ({ page, request }) => {
  const unauthorized = await request.get("/api/hotel");
  expect(unauthorized.status()).toBe(401);
  await page.goto("/anomalies");
  await page.getByLabel("Mot de passe · Employé").fill("test-employee");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await page.getByRole("button", { name: "Signaler une anomalie", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await expect(dialog.getByLabel("Responsable de l’intervention")).toHaveCount(0);
  await expect(dialog.getByLabel("Signalé par")).toHaveCount(1);
  const jpeg = await page.evaluate(() => {
    const canvas = document.createElement("canvas");
    canvas.width = canvas.height = 20;
    const context = canvas.getContext("2d")!;
    context.fillStyle = "red";
    context.fillRect(0, 0, 20, 20);
    return canvas.toDataURL("image/jpeg").split(",")[1];
  });
  const file = { name: "photo.jpg", mimeType: "image/jpeg", buffer: Buffer.from(jpeg, "base64") };
  const picker = dialog.locator('input[type="file"][multiple]');
  await picker.setInputFiles([file, file, file, file]);
  await expect(dialog.getByText("Ajoutez au maximum 3 photos.")).toBeVisible();
  await picker.setInputFiles([file, file, file]);
  await expect(dialog.getByText("3 / 3 photos · facultatif")).toBeVisible();
  await dialog.getByRole("button", { name: "Retirer la photo 2" }).click();
  await expect(dialog.getByText("2 / 3 photos · facultatif")).toBeVisible();
  await dialog.locator('input[capture="environment"]').setInputFiles(file);
  await expect(dialog.getByText("3 / 3 photos · facultatif")).toBeVisible();
  await dialog.getByLabel("Description du problème").fill("Fuite de test");
  await dialog.getByLabel("Titre").fill("Test trois photos");
  await dialog.getByLabel("Lieu précis").fill("Chambre 204");
  await dialog.getByLabel("Signalé par").fill("  Employé test  ");
  await dialog.getByRole("button", { name: "Enregistrer l’anomalie", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole("button", { name: "Consulter", exact: true }).click();
  await expect(dialog.getByLabel("Titre")).toBeDisabled();
  await expect(dialog.getByLabel("État de résolution")).toHaveCount(0);
  await expect(dialog.getByText("Responsable : Employé test", { exact: true })).toBeVisible();
  await expect(dialog.getByRole("button", { name: "Enregistrer le suivi" })).toHaveCount(0);
  await expect(dialog.locator("img")).toHaveCount(3);
  for (const img of await dialog.locator("img").all())
    await expect(img).toHaveJSProperty("naturalWidth", 20);
  const state = await (await page.request.get("/api/hotel")).json();
  const issue = state.issues[0];
  expect(issue.reportedBy).toBe("Employé test");
  expect(issue.assignee).toBe("Employé test");
  expect(issue.history[0].actor).toBe("Employé test");
  expect(issue.history[0].assignee).toBe("Employé test");
  const photoUrl = `/api/photos/${issue.id}?index=0`;
  const firstPhoto = await page.request.get(photoUrl);
  expect(firstPhoto.status()).toBe(200);
  const etag = firstPhoto.headers().etag;
  expect(etag).toBeTruthy();
  expect(firstPhoto.headers()["cache-control"]).toBe("private, no-cache");
  expect(firstPhoto.headers()["vary"]).toContain("Cookie");
  expect(firstPhoto.headers()["cdn-cache-control"]).toBe("no-store");
  const cachedPhoto = await page.request.get(photoUrl, { headers: { "If-None-Match": etag } });
  expect(cachedPhoto.status()).toBe(304);
  expect(cachedPhoto.headers()["cache-control"]).toBe("private, no-cache");
  const update = { type: "updateIssue", id: issue.id, version: 1, actor: "Test", note: "Réparé", fields: issue, status: "resolu" };
  for (const method of ["POST", "PATCH"]) {
    const denied = await page.request.fetch("/api/hotel", { method, data: update });
    expect(denied.status()).toBe(403);
  }
  await dialog.getByRole("button", { name: "Fermer", exact: true }).click();
  await page.getByRole("button", { name: "Déconnexion", exact: true }).click();
  await expect(page.getByLabel("Profil", { exact: true })).toBeVisible();
  const privatePhoto = await page.request.get(photoUrl, { headers: { "If-None-Match": etag } });
  expect(privatePhoto.status()).toBe(401);
  await page.getByLabel("Profil", { exact: true }).click();
  await page.getByRole("option", { name: "Direction", exact: true }).click();
  await page.getByLabel("Mot de passe · Direction").fill("test-employee");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await expect(page.getByText("Mot de passe incorrect.")).toBeVisible();
  await page.getByLabel("Mot de passe · Direction").fill("test-direction");
  await page.getByRole("button", { name: "Se connecter", exact: true }).click();
  await page.getByRole("button", { name: "Ouvrir le suivi", exact: true }).click();
  await expect(dialog.getByLabel("Responsable de l’intervention")).toHaveCount(0);
  await expect(dialog.getByLabel("Intervention saisie par")).toHaveValue("");
  await dialog.getByLabel("Intervention saisie par").fill("Direction test");
  await dialog.getByRole("radiogroup", { name: "État de résolution", exact: true }).getByRole("radio", { name: "Résolu", exact: true }).click();
  await dialog.getByLabel("Travaux effectués / résolution").fill("Fuite réparée");
  await dialog.getByRole("button", { name: "Enregistrer le suivi", exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const saved = await (await page.request.get("/api/hotel")).json();
  expect(saved.issues[0].status).toBe("resolu");
  expect(saved.issues[0].reportedBy).toBe("Employé test");
  expect(saved.issues[0].assignee).toBe("Employé test");
  expect(saved.issues[0].history.at(-1).actor).toBe("Direction test");
  expect(saved.issues[0].history.at(-1).assignee).toBe("Employé test");
  expect(saved.issues[0].history[0]).toEqual(issue.history[0]);
  expect(saved.issues[0].photoIds).toHaveLength(3);
  await page.reload();
  await expect(page.getByRole("button", { name: "Déconnexion" })).toBeVisible();
});

test("photo galleries load on demand, reserve their space and recover a failed attachment", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.request.post("/api/session", { data: { role: "employe", password: "test-employee" } });
  const now = new Date().toISOString();
  const issue: Issue = {
    id: crypto.randomUUID(), version: 1, title: "Galerie photo test", location: "Chambre 203", description: "Éclairage du lavabo à vérifier.",
    category: "Électricité", priority: "normale", status: "ouvert", date: today(), createdAt: now, updatedAt: now,
    reportedBy: "Test", assignee: "Test", history: [], photoId: "photo-1", photoIds: ["photo-1", "photo-2", "photo-3"],
  };
  await page.route("**/api/hotel*", route => route.fulfill({ json: { issues: [issue], inspections: [], mode: "local" } }));
  const image = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAIAAAACCAIAAAD91JpzAAAAEklEQVR4nGP4z8DAAMIM/4EAAB/uBfsL2WiLAAAAAElFTkSuQmCC", "base64");
  const requests: number[] = [];
  let releaseFirst!: () => void;
  const firstReady = new Promise<void>(resolve => { releaseFirst = resolve; });
  let failLast = true;
  await page.route("**/api/photos/**", async route => {
    const url = new URL(route.request().url()), index = Number(url.searchParams.get("index"));
    expect(url.searchParams.get("v")).toBe("2");
    requests.push(index);
    if (index === 0) await firstReady;
    await route.fulfill(index === 2 && failLast ? { status: 503, body: "Temporary failure" } : { contentType: "image/png", body: image });
  });
  await page.goto("/anomalies");
  const card = page.getByRole("article", { name: "Chambre 203 · Galerie photo test", exact: true });
  await expect(card).toBeVisible();
  expect(requests).toHaveLength(0);
  await card.getByRole("button", { name: "Voir les photos (3)", exact: true }).click();
  const frames = card.locator("[aria-busy]");
  await frames.first().scrollIntoViewIfNeeded();
  let reservedHeight = 0;
  try {
    await expect(card.getByText("Chargement de la photo 1…", { exact: true })).toBeVisible();
    reservedHeight = (await frames.first().boundingBox())!.height;
    expect(reservedHeight).toBe(220);
  } finally { releaseFirst(); }
  await expect(card.getByRole("img", { name: "Galerie photo test · photo 1", exact: true })).toHaveJSProperty("naturalWidth", 2);
  await expect(frames.first()).toHaveAttribute("aria-busy", "false");
  expect((await frames.first().boundingBox())!.height).toBe(reservedHeight);
  await frames.nth(2).scrollIntoViewIfNeeded();
  const retry = card.getByRole("button", { name: "Réessayer la photo 3", exact: true });
  await expect.poll(() => requests.filter(index => index === 2).length).toBe(3);
  await expect(retry).toBeVisible();
  expect((await frames.nth(2).boundingBox())!.height).toBe(reservedHeight);
  failLast = false;
  await retry.click();
  await expect(card.getByRole("img", { name: "Galerie photo test · photo 3", exact: true })).toHaveJSProperty("naturalWidth", 2);
  await expect(retry).toHaveCount(0);
  expect(requests.filter(index => index === 0)).toHaveLength(1);
  await card.getByRole("button", { name: "Agrandir : Galerie photo test · photo 1", exact: true }).click();
  const enlarged = page.getByRole("dialog", { name: /^Galerie photo test · photo / });
  await expect(enlarged.getByRole("img", { name: "Galerie photo test · photo 1", exact: true })).toHaveJSProperty("naturalWidth", 2);
  await expect(enlarged.getByRole("button", { name: "Photo précédente", exact: true })).toBeDisabled();
  await enlarged.getByRole("button", { name: "Photo suivante", exact: true }).click();
  await expect(enlarged.getByRole("status").filter({ hasText: "Photo 2 sur 3" })).toBeVisible();
  await expect(enlarged.getByRole("img", { name: "Galerie photo test · photo 2", exact: true })).toHaveJSProperty("naturalWidth", 2);
  await page.keyboard.press("ArrowRight");
  await expect(enlarged.getByRole("img", { name: "Galerie photo test · photo 3", exact: true })).toHaveJSProperty("naturalWidth", 2);
  await expect(enlarged.getByRole("button", { name: "Photo suivante", exact: true })).toBeDisabled();
  await expect(enlarged.getByRole("link", { name: "Ouvrir en taille originale", exact: true })).toHaveAttribute("href", /\/api\/photos\/.*[?&]index=2(?:&|$)/);
  await page.keyboard.press("ArrowLeft");
  await expect(enlarged.getByRole("status").filter({ hasText: "Photo 2 sur 3" })).toBeVisible();
  await enlarged.getByRole("button", { name: "Fermer", exact: true }).click();
  await expect(enlarged).toHaveCount(0);
  await expect(page.locator("body")).toHaveJSProperty("scrollWidth", 390);
});
